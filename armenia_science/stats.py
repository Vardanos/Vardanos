"""Aggregate harvested works into CSV tables and a Markdown summary."""

import csv
from collections import Counter, defaultdict
from pathlib import Path

from .storage import iter_works

# Country names for the summary; anything missing falls back to the ISO code.
COUNTRY_NAMES = {
    "US": "United States", "RU": "Russia", "DE": "Germany", "FR": "France", "IT": "Italy",
    "GB": "United Kingdom", "CH": "Switzerland", "ES": "Spain", "PL": "Poland", "CN": "China",
    "JP": "Japan", "GE": "Georgia", "IR": "Iran", "UA": "Ukraine", "BY": "Belarus", "KZ": "Kazakhstan",
    "CZ": "Czechia", "NL": "Netherlands", "AT": "Austria", "SE": "Sweden", "BR": "Brazil",
    "IN": "India", "CA": "Canada", "AU": "Australia", "TR": "Türkiye", "GR": "Greece", "PT": "Portugal",
    "BE": "Belgium", "KR": "South Korea", "IL": "Israel", "FI": "Finland", "HU": "Hungary",
}


def compute(works):
    by_year = defaultdict(lambda: {"works": 0, "oa_works": 0, "citations": 0, "international": 0, "industry": 0})
    by_field, by_type, by_inst, by_country, by_venue = Counter(), Counter(), Counter(), Counter(), Counter()
    by_sector, inst_names, inst_types = Counter(), {}, {}
    for w in works:
        y = by_year[w["year"]]
        y["works"] += 1
        y["oa_works"] += bool(w.get("is_oa"))
        y["citations"] += w.get("cited_by_count") or 0
        foreign = [c for c in w.get("countries") or [] if c != "AM"]
        y["international"] += bool(foreign)
        y["industry"] += bool(w.get("has_company"))
        by_country.update(foreign)
        by_field[w.get("field") or "Unclassified"] += 1
        by_type[w.get("type") or "unknown"] += 1
        if w.get("venue"):
            by_venue[w["venue"]] += 1
        am = w.get("armenian_institutions") or []
        by_sector.update({i.get("type") or "unknown" for i in am})
        for i in am:
            by_inst[i["id"]] += 1
            inst_names[i["id"]] = i["name"]
            inst_types[i["id"]] = i.get("type") or "unknown"
    return {
        "by_year": dict(sorted(by_year.items(), key=lambda kv: kv[0] or 0)),
        "by_field": by_field, "by_type": by_type, "by_country": by_country, "by_venue": by_venue,
        "by_institution": by_inst, "institution_names": inst_names, "institution_types": inst_types,
        "by_sector": by_sector,
    }


def _write_csv(path, header, rows):
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def _pct(n, d):
    return f"{100 * n / d:.1f}%" if d else "–"


def write(s, out_dir, summary_path):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    _write_csv(out / "by_year.csv", ["year", "works", "oa_works", "international_works", "industry_works", "citations"],
               [[y, v["works"], v["oa_works"], v["international"], v["industry"], v["citations"]]
                for y, v in s["by_year"].items()])
    _write_csv(out / "by_sector.csv", ["sector", "works"], s["by_sector"].most_common())
    _write_csv(out / "by_field.csv", ["field", "works"], s["by_field"].most_common())
    _write_csv(out / "by_type.csv", ["type", "works"], s["by_type"].most_common())
    _write_csv(out / "by_venue.csv", ["venue", "works"], s["by_venue"].most_common())
    _write_csv(out / "collaborating_countries.csv", ["country", "works"], s["by_country"].most_common())
    _write_csv(out / "by_institution.csv", ["openalex_id", "institution", "type", "works"],
               [[i, s["institution_names"][i], s["institution_types"][i], n] for i, n in s["by_institution"].most_common()])

    total = sum(v["works"] for v in s["by_year"].values())
    lines = ["# Armenia's scientific output — summary", "",
             "_Generated by `python -m armenia_science stats` from OpenAlex data in `data/works/`._", "",
             f"**Total works:** {total:,}", "", "## Works per year", "",
             "| Year | Works | Open access | International co-authorship | With industry | Citations |",
             "|---:|---:|---:|---:|---:|---:|"]
    for y, v in s["by_year"].items():
        lines.append(f"| {y} | {v['works']:,} | {_pct(v['oa_works'], v['works'])} | "
                     f"{_pct(v['international'], v['works'])} | {_pct(v['industry'], v['works'])} | {v['citations']:,} |")
    sections = [
        ("Output by sector of the Armenian institution", "Sector", s["by_sector"].most_common()),
        ("Top Armenian companies", "Company",
         [(s["institution_names"][i], n) for i, n in s["by_institution"].most_common()
          if s["institution_types"][i] == "company"][:20]),
        ("Top research fields", "Field", [(k, n) for k, n in s["by_field"].most_common(15)]),
        ("Top Armenian institutions", "Institution",
         [(s["institution_names"][i], n) for i, n in s["by_institution"].most_common(20)]),
        ("Top collaborating countries", "Country",
         [(COUNTRY_NAMES.get(c, c), n) for c, n in s["by_country"].most_common(20)]),
        ("Top venues", "Venue", s["by_venue"].most_common(15)),
    ]
    for title, col, rows in sections:
        lines += ["", f"## {title}", "", f"| {col} | Works |", "|---|---:|"]
        lines += [f"| {k} | {n:,} |" for k, n in rows]
    Path(summary_path).write_text("\n".join(lines) + "\n", encoding="utf-8")


def run(data_dir, summary_path):
    s = compute(iter_works(Path(data_dir) / "works"))
    write(s, Path(data_dir) / "stats", summary_path)
    return s
