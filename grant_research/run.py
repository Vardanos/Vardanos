"""Apply one experiment to pool.jsonl, keep it if relevance@100 improves.

    python run.py experiments/007.json   # run one experiment
    python run.py --replay               # rebuild pool + results from all experiments
    python run.py --report               # write shortlist.csv / SHORTLIST.md

An experiment file is {"id", "hypothesis", "kind": "add" | "verify",
"add": [records], "update": {id: {field: value}}, "remove": [ids]}.
"add" experiments are kept only if the metric strictly improves; otherwise the
pool is reverted and the candidates are logged to rejected.jsonl. "verify"
experiments correct facts and are always kept, even when the metric drops -
the metric is only meaningful if the data is true.
"""

import csv
import json
import sys
from pathlib import Path

import evaluate

HERE = Path(__file__).parent
RESULTS = HERE / "results.tsv"
REJECTED = HERE / "rejected.jsonl"
HEADER = "exp\trelevance@100\tdelta\tpool_size\tstatus\tdescription\n"


def save(pool, path=evaluate.POOL):
    path.write_text("".join(json.dumps(r, ensure_ascii=False, sort_keys=True) + "\n"
                            for r in sorted(pool, key=lambda r: r["id"])))


def apply(pool, exp):
    by_id = {r["id"]: dict(r) for r in pool}
    for rid in exp.get("remove", []):
        del by_id[rid]
    for rid, fields in exp.get("update", {}).items():
        by_id[rid].update(fields)
    for rec in exp.get("add", []):
        if rec["id"] in by_id:
            raise ValueError(f"{exp['id']}: {rec['id']} already in pool")
        by_id[rec["id"]] = rec
    return list(by_id.values())


def run(path):
    exp = json.loads(Path(path).read_text())
    pool = evaluate.load()
    before = evaluate.relevance_at_k(pool)
    new_pool = apply(pool, exp)
    after = evaluate.relevance_at_k(new_pool)  # raises on schema errors -> crash
    if exp["kind"] == "verify":
        status = "keep" if after >= before else "fix"
    else:
        status = "keep" if after > before + 1e-9 else "discard"
    if status == "discard":
        with REJECTED.open("a") as f:
            for rec in exp.get("add", []):
                f.write(json.dumps({"exp": exp["id"], **rec}, ensure_ascii=False) + "\n")
        after = before
    else:
        save(new_pool)
    if not RESULTS.exists():
        RESULTS.write_text(HEADER)
    with RESULTS.open("a") as f:
        f.write(f"{exp['id']}\t{after:.6f}\t{after - before:+.6f}\t"
                f"{len(new_pool) if status != 'discard' else len(pool)}\t{status}\t{exp['hypothesis']}\n")
    print(f"{exp['id']} {status:7s} {before:.6f} -> {after:.6f}  {exp['hypothesis']}")


def report():
    ranked = evaluate.rank(evaluate.load())[:evaluate.TOP_K]
    cols = ["rank", "score", "funder", "program", "max_award_usd", "eligibility", "topic",
            "instrument", "geo", "status", "verified", "url", "notes"]
    with (HERE / "shortlist.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(cols)
        for i, r in enumerate(ranked, 1):
            w.writerow([i, f"{evaluate.score(r):.3f}"] + [r.get(c) for c in cols[2:]])
    lines = ["# Top 100 grant sources for Denovo Sciences\n",
             "Generated by `python run.py --report`; see README.md for method.\n",
             "| # | Score | Funder — programme | Max award (USD) | Applicant route | Notes |",
             "|---|---|---|---|---|---|"]
    for i, r in enumerate(ranked, 1):
        award = f"{r['max_award_usd']:,.0f}" if r.get("max_award_usd") else "varies"
        lines.append(f"| {i} | {evaluate.score(r):.3f} | [{r['funder']} — {r['program']}]({r['url']}) "
                     f"| {award} | {r['eligibility'].replace('_', ' ')} | {r['notes']} |")
    (HERE / "SHORTLIST.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    if sys.argv[1] == "--replay":
        for p in (evaluate.POOL, RESULTS, REJECTED):
            p.unlink(missing_ok=True)
        for p in sorted((HERE / "experiments").glob("*.json")):
            run(p)
    elif sys.argv[1] == "--report":
        report()
    else:
        run(sys.argv[1])
